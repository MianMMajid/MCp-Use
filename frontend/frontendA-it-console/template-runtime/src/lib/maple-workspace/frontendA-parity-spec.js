export function aggregateParityStatus(statuses) {
  const normalized = uniqueList(statuses)
  if (normalized.length === 0) return 'missing'
  if (normalized.every((status) => status === 'retired')) return 'retired'
  if (normalized.includes('missing')) return 'missing'
  if (normalized.includes('partial')) return 'partial'
  return 'implemented'
}

export const FRONTEND_A_PARITY_BY_ROUTE = Object.freeze(
  Object.fromEntries(
    uniqueList(FRONTEND_A_PARITY_CAPABILITIES.map((item) => item.frontendRoute)).map((frontendRoute) => {
      const capabilities = FRONTEND_A_PARITY_CAPABILITIES.filter((item) => item.frontendRoute === frontendRoute)
      return [frontendRoute, Object.freeze({
        frontendRoute,
        capabilityIds: capabilities.map((item) => item.capabilityId),
        securityDomains: uniqueList(capabilities.map((item) => item.securityDomain)),
        cliCommands: uniqueList(capabilities.flatMap((item) => item.cliCommands)),
        legacySource: uniqueList(capabilities.map((item) => item.legacySource)),
        parityStatus: aggregateParityStatus(capabilities.map((item) => item.status)),
        svelteSurfaces: uniqueList(capabilities.map((item) => item.svelteSurface)),
        capabilities,
      })]
    }),
  ),
)

export function getFrontendAParityForRoute(frontendRoute) {
  return FRONTEND_A_PARITY_BY_ROUTE[frontendRoute] ?? null
}

